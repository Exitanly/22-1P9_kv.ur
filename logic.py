"""Алгоритм решения квадратного уравнения."""


def kvur_dis_zero(a, b, c):
    """Алгоритм решения квадратных уравнений. Дискриминант равен нулю"""
    d = b**2 - 4*a*c
    if d == 0:
        x = -b/2*a
        return "Квадратное уравнение. Дискриминант равен нулю. Один корень", x
    return tuple("Ошибка")


def kvur(a, b, c):
    """Алгоритм решения квадратного уравнения."""
    d = b ** 2 - 4 * a * c
    if d > 0:
        x1 = (-b + d ** 0.5) / (2 * a)
        x2 = (-b - d ** 0.5) / (2 * a)
        return ("Квадратное уравнение. D >0. Два корня уравнения", d, x1, x2)
    return ("Ошибка",)
